//! Gravity source lints: allocation sites and the kernel boundary (docs/gravity/lint.md).
pub mod asm_loop;

use std::fs;
use std::path::{Path, PathBuf};

pub const NO_ALLOC_CRATES: &[&str] = &["abi", "driver", "kernels", "parallel", "pool", "hosts", "wire", "exec", "dict"];
/// Carried v1 crates (milestone-2.md §2.6 item 3): `crate_dirs()` leaves them out.
pub const CARRIED_V1_CRATES: &[&str] = &["ir", "backend"];
pub const ALLOC_PATTERNS: &[&str] = &["Vec::new(", "vec![", "Box::new(", "String::from(", ".to_string()", "format!("];
pub const ALLOC_LIFETIMES: &[&str] = &["Program", "Node", "Exec", "Cold"];

/// The `crates/gravity` directory of the checkout under test: the parent of [`lint_dir`].
pub fn gravity_root() -> PathBuf {
    lint_dir().parent().unwrap().to_path_buf()
}

/// This crate's directory in the checkout under test (D793). Read at run time from the `CARGO_MANIFEST_DIR` cargo sets for
/// the test process, never from the path baked in at compile time: a test binary reused from another checkout's build (a
/// kache hit, a shared target dir) otherwise scanned THAT tree and passed on a tree it never read (kernel_boundary on
/// M6-HOSTS's H2, 09-26). Panics, naming both paths, when the run-time directory is missing or is not gravity_lint's.
pub fn lint_dir() -> PathBuf {
    let run = std::env::var_os("CARGO_MANIFEST_DIR").map(PathBuf::from);
    root_from(env!("CARGO_MANIFEST_DIR"), run.as_deref()).unwrap_or_else(|e| panic!("gravity_lint: {e}"))
}

/// [`lint_dir`]'s rule over its two inputs: the compile-time directory `built` and the run-time `run`. -> `run` when it is a
/// gravity_lint crate directory (its Cargo.toml names the package), whatever `built` says; an error naming both otherwise.
pub fn root_from(built: &str, run: Option<&Path>) -> Result<PathBuf, String> {
    let Some(run) = run else {
        return Err(format!("CARGO_MANIFEST_DIR is not set at run time: run the lints with `cargo test` in the checkout under test (this binary was built in {built})"));
    };
    let toml = fs::read_to_string(run.join("Cargo.toml")).unwrap_or_default();
    if !toml.lines().any(|l| l.trim() == "name = \"gravity_lint\"") {
        return Err(format!("the run-time CARGO_MANIFEST_DIR {} is not gravity_lint's directory (this binary was built in {built})", run.display()));
    }
    if Path::new(built) != run {
        eprintln!("gravity_lint: this binary was built in {built}; scanning the checkout under test, {}", run.display());
    }
    Ok(run.to_path_buf())
}

pub fn crate_dirs() -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = fs::read_dir(gravity_root())
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.join("Cargo.toml").is_file())
        .filter(|p| !CARRIED_V1_CRATES.iter().any(|c| p.file_name().is_some_and(|n| n == *c)))
        .collect();
    dirs.sort();
    dirs
}

pub fn rust_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    walk(dir, &mut out);
    out.sort();
    out
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        let name = path.file_name().unwrap().to_string_lossy().into_owned();
        if path.is_dir() {
            if name == "target" || (name == "golden" && dir.file_name().unwrap() == "tests") {
                continue;
            }
            walk(&path, out);
        } else if name.ends_with(".rs") && !is_generated(&path) {
            out.push(path);
        }
    }
}

fn is_generated(path: &Path) -> bool {
    let text = fs::read_to_string(path).unwrap();
    text.lines().take(5).any(|l| l.contains("@generated") || l.contains("generated by"))
}

pub fn rel(path: &Path) -> String {
    path.strip_prefix(gravity_root().parent().unwrap().parent().unwrap()).unwrap_or(path).display().to_string()
}

pub struct AllocSite {
    pub path: PathBuf,
    pub line_no: usize,
    pub pattern: &'static str,
    pub line: String,
}

/// The charged marker (wave 2 rulings R1 + R5): `// alloc: <lifetime> charged <owner expr>` says the line's bytes are charged
/// to that memledger owner (a `ChargedVec`, a hand-rolled `Charge`). alloclint's ratchet reads such a line as tracked.
pub const ALLOC_CHARGED: &str = "charged";

/// The tag after the line's last `// alloc:`: a lifetime of [`ALLOC_LIFETIMES`] alone, or the lifetime, the charged marker
/// and a non-empty owner expression (`Exec charged stmt_owner`). Anything else (another word, a comma, a bare `charged`) fails.
pub fn alloc_tag_ok(line: &str) -> bool {
    let Some((_, tag)) = line.rsplit_once("// alloc:") else { return false };
    let tag = tag.trim();
    let (life, rest) = match tag.split_once(char::is_whitespace) {
        Some((life, rest)) => (life, Some(rest.trim_start())),
        None => (tag, None),
    };
    ALLOC_LIFETIMES.contains(&life)
        && rest.is_none_or(|r| r.strip_prefix(ALLOC_CHARGED).is_some_and(|o| o.starts_with(char::is_whitespace) && !o.trim().is_empty()))
}

/// The owner expression of a charged tag (`// alloc: Exec charged <owner expr>`), None for a plain lifetime tag or no tag.
pub fn alloc_charged_owner(line: &str) -> Option<&str> {
    if !alloc_tag_ok(line) {
        return None;
    }
    let (_, tag) = line.rsplit_once("// alloc:")?;
    let (_, rest) = tag.trim().split_once(char::is_whitespace)?;
    Some(rest.trim_start().strip_prefix(ALLOC_CHARGED)?.trim())
}

pub fn alloc_sites(crate_dir: &Path) -> Vec<AllocSite> {
    let mut out = Vec::new();
    for path in rust_files(&crate_dir.join("src")) {
        let text = fs::read_to_string(&path).unwrap();
        let code = code_only(&text);
        for (i, (line, code_line)) in text.lines().zip(code.lines()).enumerate() {
            if let Some(pattern) = alloc_pattern(code_line) {
                if !alloc_tag_ok(line) {
                    out.push(AllocSite { path: path.clone(), line_no: i + 1, pattern, line: line.trim().to_owned() });
                }
            }
        }
    }
    out
}

/// The first [`ALLOC_PATTERNS`] entry a line of CODE names (comments and literals already blanked by [`code_only`]): a pattern
/// that starts with an identifier character must start a path segment, so `Vec::new(` matches `Vec::new(` and
/// `std::vec::Vec::new(` but not `ChargedVec::new(` / `PgVec::new(` / `ArenaVec::new(` (a charged or context-allocated
/// constructor is no std allocation; TD-197 LINT-FP, memacct 2026-10-15T20:4xZ).
pub fn alloc_pattern(code_line: &str) -> Option<&'static str> {
    let ident = |c: char| c.is_alphanumeric() || c == '_';
    ALLOC_PATTERNS.iter().copied().find(|p| {
        let anchored = p.starts_with(ident);
        code_line.match_indices(p).any(|(i, _)| !anchored || !code_line[..i].ends_with(ident))
    })
}

/// The source with its comments (line, doc, nested block) and its string / char literals' contents replaced by spaces, newlines
/// kept: line `k` of the result is line `k`'s code. A pattern in a doc comment or a message names no allocation.
pub fn code_only(text: &str) -> String {
    let b = text.as_bytes();
    let mut out = b.to_vec();
    let n = b.len();
    let wipe = |out: &mut Vec<u8>, a: usize, z: usize| {
        for c in out.iter_mut().take(z.min(n)).skip(a) {
            if *c != b'\n' {
                *c = b' ';
            }
        }
    };
    let ident = |c: u8| c.is_ascii_alphanumeric() || c == b'_';
    let mut i = 0;
    while i < n {
        let c = b[i];
        if c == b'/' && i + 1 < n && b[i + 1] == b'/' {
            let z = b[i..].iter().position(|&x| x == b'\n').map_or(n, |k| i + k);
            wipe(&mut out, i, z);
            i = z;
        } else if c == b'/' && i + 1 < n && b[i + 1] == b'*' {
            let (mut depth, mut j) = (1, i + 2);
            while j < n && depth > 0 {
                if b[j..].starts_with(b"/*") {
                    depth += 1;
                    j += 2;
                } else if b[j..].starts_with(b"*/") {
                    depth -= 1;
                    j += 2;
                } else {
                    j += 1;
                }
            }
            wipe(&mut out, i, j);
            i = j;
        } else if (c == b'r' || c == b'b') && (i == 0 || !ident(b[i - 1])) && raw_start(&b[i..]).is_some() {
            let (open, hashes) = raw_start(&b[i..]).unwrap();
            let mut close = vec![b'"'];
            close.extend(std::iter::repeat_n(b'#', hashes));
            let body = i + open;
            let z = b[body..].windows(close.len()).position(|w| w == close.as_slice()).map_or(n, |k| body + k + close.len());
            wipe(&mut out, body, z.saturating_sub(close.len()).max(body));
            i = z;
        } else if c == b'"' {
            let mut j = i + 1;
            while j < n && b[j] != b'"' {
                j += if b[j] == b'\\' { 2 } else { 1 };
            }
            wipe(&mut out, i + 1, j.min(n));
            i = j + 1;
        } else if c == b'\'' {
            // a char literal ('x', '\n', '\u{..}'); a lifetime ('a) is left
            if i + 3 < n && b[i + 1] == b'\\' {
                // the escaped character itself may be a quote ('\''): the closing quote comes after it
                let z = b[i + 3..].iter().position(|&x| x == b'\'').map_or(n, |k| i + 3 + k);
                wipe(&mut out, i + 1, z);
                i = z + 1;
            } else if i + 2 < n && b[i + 2] == b'\'' {
                wipe(&mut out, i + 1, i + 2);
                i += 3;
            } else {
                i += 1;
            }
        } else {
            i += 1;
        }
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// A raw (byte) string's opening at the slice's start: (its length through the quote, the number of '#')
fn raw_start(s: &[u8]) -> Option<(usize, usize)> {
    let k = if s.starts_with(b"br") { 2 } else if s.starts_with(b"r") { 1 } else { return None };
    let hashes = s[k..].iter().take_while(|&&c| c == b'#').count();
    (s.get(k + hashes) == Some(&b'"')).then_some((k + hashes + 1, hashes))
}

/// The kernel boundary (docs/gravity/abi-v2.md §0): `gravity_kernels` depends on the ABI (the
/// `#[repr(C)]` blocks and the breaker layouts) and the dictionary library and on nothing else of
/// Gravity's; no kernel source names another Gravity crate (the hand programs live in `gravity_program::hand`).
pub const KERNEL_CRATE: &str = "kernels";
pub const KERNEL_ALLOWED_DEPS: &[&str] = &["gravity_abi", "gravity_dict", "gravity_fn"];
pub const KERNEL_FORBIDDEN_PATHS: &[&str] = &["gravity_program", "gravity_driver", "gravity_hosts", "gravity_exec", "gravity_parallel", "gravity_pool", "gravity_wire"];

/// The `[dependencies]` keys of a crate's Cargo.toml (dev-dependencies are not the boundary).
pub fn cargo_dependencies(crate_dir: &Path) -> Vec<String> {
    let text = fs::read_to_string(crate_dir.join("Cargo.toml")).unwrap();
    let mut in_deps = false;
    let mut out = Vec::new();
    for line in text.lines() {
        let l = line.trim();
        if l.starts_with('[') {
            in_deps = l == "[dependencies]";
            continue;
        }
        if in_deps && !l.is_empty() && !l.starts_with('#') {
            if let Some((k, _)) = l.split_once('=') {
                out.push(k.trim().to_owned());
            }
        }
    }
    out
}

pub fn kernel_boundary_violations() -> Vec<String> {
    let dir = gravity_root().join(KERNEL_CRATE);
    let mut out = Vec::new();
    for dep in cargo_dependencies(&dir) {
        if !KERNEL_ALLOWED_DEPS.contains(&dep.as_str()) {
            out.push(format!("{}/Cargo.toml: dependency `{dep}` is outside the kernel boundary ({})", rel(&dir), KERNEL_ALLOWED_DEPS.join(", ")));
        }
    }
    for path in rust_files(&dir.join("src")) {
        for (i, line) in fs::read_to_string(&path).unwrap().lines().enumerate() {
            if let Some(name) = KERNEL_FORBIDDEN_PATHS.iter().find(|n| line.contains(*n)) {
                out.push(format!("{}:{}: names `{name}`", rel(&path), i + 1));
            }
        }
    }
    out
}
